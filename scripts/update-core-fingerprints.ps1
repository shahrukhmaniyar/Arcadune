# Regenerates CoreFingerprints.kt from the sha256 fingerprints GitHub keeps for every release file.
# Run it after uploading a new "cores-N" or "psp-files-N" release, then rebuild the app:
#   powershell -ExecutionPolicy Bypass -File scripts/update-core-fingerprints.ps1 -CoresVersion 2 -PspVersion 1
param(
    [string]$CoresVersion = "2",
    [string]$PspVersion = "1",
    [string]$Repo = "shahrukhmaniyar/Arcadune"
)
$ErrorActionPreference = "Stop"

function Get-Digests([string]$tag) {
    $release = gh api "repos/$Repo/releases/tags/$tag" | ConvertFrom-Json
    $missing = @($release.assets | Where-Object { -not $_.digest })
    if ($missing.Count -gt 0) { throw "Release $tag has files without a fingerprint: $($missing.name -join ', ')" }
    $release.assets | Sort-Object name | ForEach-Object { [pscustomobject]@{ Name = $_.name; Sha = $_.digest -replace '^sha256:', '' } }
}

$cores = Get-Digests "cores-$CoresVersion"
$psp = Get-Digests "psp-files-$PspVersion" | Where-Object Name -eq 'ppsspp.zip'
if (-not $psp) { throw "psp-files-$PspVersion has no ppsspp.zip" }

$lines = @()
$lines += 'package com.swordfish.lemuroid.lib.core'
$lines += ''
$lines += '/**'
$lines += ' * SHA-256 of every file Arcadune downloads and runs, taken from its GitHub release.'
$lines += ' * Generated by scripts/update-core-fingerprints.ps1: do not edit by hand.'
$lines += ' */'
$lines += 'object CoreFingerprints {'
$lines += "    const val CORES_RELEASE = `"cores-$CoresVersion`""
$lines += "    const val PPSSPP_ASSETS_RELEASE = `"psp-files-$PspVersion`""
$lines += "    const val PPSSPP_ASSETS_SHA256 = `"$($psp.Sha)`""
$lines += ''
$lines += '    /** "<abi>__<library>.so" to its SHA-256. */'
$lines += '    val CORES: Map<String, String> ='
$lines += '        mapOf('
foreach ($c in $cores) {
    $lines += "            `"$($c.Name)`" to"
    $lines += "                `"$($c.Sha)`","
}
$lines += '        )'
$lines += '}'

$target = Join-Path $PSScriptRoot "..\retrograde-app-shared\src\main\java\com\swordfish\lemuroid\lib\core\CoreFingerprints.kt"
[System.IO.File]::WriteAllText((Resolve-Path (Split-Path $target)).Path + "\CoreFingerprints.kt", ($lines -join "`n") + "`n")
"Wrote $($cores.Count) core fingerprints and the PSP assets fingerprint."
